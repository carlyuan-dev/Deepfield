import { Type, type Static, type TSchema } from "typebox";
import { Value } from "typebox/value";
import { ConfigError } from "./config-error.js";
import { defineConfig, type ConfigDefinition } from "./definition.js";
import { DEFAULT_DEEPSEEK_MODEL_ID, LlmProfileDraftSchema, type LlmProfileDraft, type LlmProfileView, type LlmRuntimeSnapshot } from "./llm.js";
import { SearchProfileDraftSchema, type SearchProfileDraft, type SearchProfileView, type SearchRuntimeSnapshot } from "./search.js";
import type { ConfigRuntimeOptions, ConfigSecretStore } from "./ports.js";
import { createProfileCollection } from "./profiles.js";
import { ConfigRecordCore, portCall } from "./record.js";
import type { ProfileDraft, ProfileSnapshot, ProfilesView } from "./types.js";

const Id = Type.String({ minLength: 1, maxLength: 200 });
const Name = Type.String({ minLength: 1, maxLength: 120 });
const LlmValuesSchema = Type.Omit(LlmProfileDraftSchema, ["id", "name", "apiKey"]);
const SearchValuesSchema = Type.Omit(SearchProfileDraftSchema, ["id", "name", "apiKey"]);
type LlmValues = Static<typeof LlmValuesSchema>;
type SearchValues = Static<typeof SearchValuesSchema>;
const storedMetadata = { id: Id, name: Name, configRevisionId: Type.Optional(Id), credentialRef: Type.String({ minLength: 1, maxLength: 500 }) };
const StoredLlmSchema = Type.Object({ ...LlmValuesSchema.properties, ...storedMetadata }, { additionalProperties: false });
const StoredSearchSchema = Type.Object({ ...SearchValuesSchema.properties, ...storedMetadata }, { additionalProperties: false });
const StoredSettingsSchema = Type.Object({
  schemaVersion: Type.Literal(1),
  llm: Type.Object({ activeProfileId: Type.Union([Id, Type.Null()]), profiles: Type.Array(StoredLlmSchema) }, { additionalProperties: false }),
  search: Type.Object({ activeProfileId: Type.Union([Id, Type.Null()]), profiles: Type.Array(StoredSearchSchema) }, { additionalProperties: false }),
}, { additionalProperties: false });
type StoredSettings = Static<typeof StoredSettingsSchema>;
type StoredProfile = StoredSettings["llm"]["profiles"][number] | StoredSettings["search"]["profiles"][number];
type Service = "llm" | "search";
const empty = (): StoredSettings => ({ schemaVersion: 1, llm: { activeProfileId: null, profiles: [] }, search: { activeProfileId: null, profiles: [] } });

export type LegacyProfilesView = {
  schemaVersion: 1;
  llm: { activeProfileId: string | null; profiles: LlmProfileView[] };
  search: { activeProfileId: string | null; profiles: SearchProfileView[] };
};
export type LegacyProfileManagerOptions = {
  documents: { read(): unknown | undefined; write(document: unknown): void };
  secrets: ConfigSecretStore;
  newId: () => string;
  /** Host-injected legacy comparison, preserving the original options/revision semantics. */
  equalValues: (left: unknown, right: unknown) => boolean;
};

const llmDefinition = defineConfig({ key: "llm", schemaVersion: 1, schema: LlmValuesSchema,
  defaults: { provider: "deepseek", protocol: "openai_compatible", baseUrl: "https://api.deepseek.com", modelId: DEFAULT_DEEPSEEK_MODEL_ID, contextWindow: 128000 },
  secrets: { apiKey: { requiredForExecution: true } },
});
const searchDefinition = defineConfig({ key: "search", schemaVersion: 1, schema: SearchValuesSchema,
  defaults: { provider: "metaso", baseUrl: "https://metaso.cn", options: {} },
  secrets: { apiKey: { requiredForExecution: true } },
});

/** Old v1 serialization is a codec around the same collection and record behavior. */
export function createLegacyProfileManager(options: LegacyProfileManagerOptions) {
  let settings = empty();
  let initialized = false;
  const ensure = () => { if (!initialized) throw new ConfigError("not_initialized"); };
  const newId = () => portCall("new_id", {}, options.newId);
  function write(document: StoredSettings) {
    portCall("write_document", {}, () => options.documents.write(structuredClone(document)));
    settings = document;
  }

  function collection<V>(service: Service, definition: ConfigDefinition) {
    const address = { scope: "host", key: service };
    const refs = new Map<string, string>();
    function canonical(id: string): string { return new ConfigRecordCore(definition, address, ports, id).credentialRef("apiKey"); }
    function legacyRef(ref: string): string {
      const known = refs.get(ref);
      if (known !== undefined) return known;
      // This port only receives canonical references generated by the record core.
      const tuple = JSON.parse(ref.slice("config:".length)) as unknown[];
      if (tuple[0] !== address.scope || tuple[1] !== service || typeof tuple[2] !== "string" || tuple[3] !== "apiKey") {
        throw new ConfigError("invalid_document", address);
      }
      const legacy = `${service}.profile.${tuple[2]}.apiKey`;
      refs.set(ref, legacy);
      return legacy;
    }
    const ports: ConfigRuntimeOptions = {
      newId: options.newId,
      secrets: {
        has: (ref) => options.secrets.has(legacyRef(ref)),
        get: (ref) => options.secrets.get(legacyRef(ref)),
        set: (ref, value) => options.secrets.set(legacyRef(ref), value),
        delete: (ref) => { const legacy = legacyRef(ref); if (service !== "llm" || legacy !== "deepseek.apiKey") options.secrets.delete(legacy); },
      },
      documents: {
        read() {
          const group = settings[service];
          return { formatVersion: 1, kind: "profiles", schemaVersion: 1, activeProfileId: group.activeProfileId,
            profiles: group.profiles.map((profile) => {
              const { id, name, configRevisionId, credentialRef, ...values } = profile;
              const ref = canonical(id); refs.set(ref, credentialRef);
              return { id, name, revision: configRevisionId!, values: structuredClone(values), credentialRefs: { apiKey: ref } };
            }),
          };
        },
        write(_address, document) {
          const group = document as { activeProfileId: string | null; profiles: { id: string; name: string; revision: string; values: V }[] };
          const profiles = group.profiles.map(({ id, name, revision, values }): StoredProfile => ({
            ...structuredClone(values), id, name, configRevisionId: revision, credentialRef: legacyRef(canonical(id)),
          }) as StoredProfile);
          const next = { ...settings, [service]: { activeProfileId: group.activeProfileId, profiles } } as StoredSettings;
          write(next);
        },
      },
    };
    return createProfileCollection<V>(definition, address, ports, ensure, {
      cloneValues: structuredClone, equalValues: options.equalValues, deleteSecretsBeforeWrite: true,
    });
  }
  const llm = collection<LlmValues>("llm", llmDefinition);
  const search = collection<SearchValues>("search", searchDefinition);

  function draft<V>(schema: TSchema, service: Service, input: LlmProfileDraft | SearchProfileDraft): ProfileDraft<V> {
    ensure();
    if (!Value.Check(schema, input)) throw new ConfigError("invalid_values", { key: service });
    const { id, name, apiKey, ...values } = input;
    return { ...(id === undefined ? {} : { id }), name, values: values as V,
      ...(apiKey === undefined ? {} : { secrets: { apiKey } }),
    };
  }
  function view<V>(group: ProfilesView<V>) {
    return { activeProfileId: group.activeProfileId, profiles: group.profiles.map(({ id, name, values, secretStatus }) => ({
      ...values, id, name, hasCredential: secretStatus.apiKey ?? false,
    })) };
  }
  function snapshot<V>(input: ProfileSnapshot<V>) {
    return { ...input.values, id: input.profile.id, name: input.profile.name, configRevisionId: input.identity.revision,
      ...(input.identity.draftSessionId === undefined ? {} : { draftSessionId: input.identity.draftSessionId }), apiKey: input.secrets.apiKey!,
    };
  }
  async function getView(): Promise<LegacyProfilesView> {
    ensure();
    const [llmView, searchView] = await Promise.all([llm.getView(), search.getView()]);
    return { schemaVersion: 1, llm: view(llmView), search: view(searchView) };
  }
  return {
    async initialize(): Promise<void> {
      if (initialized) return;
      const input = portCall("read_document", {}, () => options.documents.read());
      if (input !== undefined) {
        if (!Value.Check(StoredSettingsSchema, input)) throw new ConfigError("invalid_document");
        settings = structuredClone(input);
        let migrated = false;
        for (const profile of settings.llm.profiles) {
          if (profile.provider === "deepseek" && profile.protocol === "openai_compatible" && profile.modelId === "deepseek-v4-flash") {
            profile.modelId = DEFAULT_DEEPSEEK_MODEL_ID; profile.configRevisionId = newId(); migrated = true;
          }
        }
        for (const profile of [...settings.llm.profiles, ...settings.search.profiles]) {
          if (!profile.configRevisionId) { profile.configRevisionId = newId(); migrated = true; }
        }
        if (migrated) write(settings);
      }
      if (settings.llm.profiles.length === 0 && portCall("has_secret", { key: "llm" }, () => options.secrets.has("deepseek.apiKey"))) {
        const id = newId();
        settings.llm.profiles.push({ id, configRevisionId: newId(), name: "DeepSeek", ...llmDefinition.defaults, credentialRef: "deepseek.apiKey" });
        settings.llm.activeProfileId = id; write(settings);
      }
      initialized = true;
    },
    getView,
    async saveLlmProfile(input: LlmProfileDraft) { await llm.save(draft<LlmValues>(LlmProfileDraftSchema, "llm", input)); return getView(); },
    async saveSearchProfile(input: SearchProfileDraft) { await search.save(draft<SearchValues>(SearchProfileDraftSchema, "search", input)); return getView(); },
    async activateLlmProfile(id: string | null) { await llm.activate(id); return getView(); },
    async activateSearchProfile(id: string | null) { await search.activate(id); return getView(); },
    async deleteLlmProfile(id: string) { await llm.delete(id); return getView(); },
    async deleteSearchProfile(id: string) { await search.delete(id); return getView(); },
    async resolveActiveLlm(): Promise<LlmRuntimeSnapshot> { return snapshot(await llm.resolveActive()); },
    async resolveActiveSearch(): Promise<SearchRuntimeSnapshot> { return snapshot(await search.resolveActive()); },
    async resolveLlmDraft(input: LlmProfileDraft): Promise<LlmRuntimeSnapshot> { return snapshot(await llm.resolveDraft(draft<LlmValues>(LlmProfileDraftSchema, "llm", input))); },
    async resolveSearchDraft(input: SearchProfileDraft): Promise<SearchRuntimeSnapshot> { return snapshot(await search.resolveDraft(draft<SearchValues>(SearchProfileDraftSchema, "search", input))); },
  };
}
